'''
Faça um programa que peça uma temperatura em graus
Celsius, converta-a para Fahrenheit e mostre o re
sultado.
Fórmula: F = (C × 9/5) + 32.
Resposta / código:
'''
Celsius = float(input(" Digite a temperatura em Celsius: "))
Celsius = Celsius * 1.8
Fahrenheit = Celsius + 32 
print("O valor específico em Fahrenheit é", Fahrenheit)
